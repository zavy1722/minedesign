"""Landmark shape priors: the ``LandmarkPrior`` protocol, ``FactorPrior``, ``DiagonalPrior``, ``CompositePrior``.

Implements DESIGN D-03, D-04 and 4.6 (FactorPrior part); data from the packaged
prior ``face3d/data/landmark_prior_v1.json`` (DESIGN 3.2), itself generated by
``tools/build_prior_tables.py`` from the research note *metric-3d-landmark-reference*.

Conventions
-----------
* Coordinates are float64 millimetres in the Frankfort-horizontal head frame of
  the prior mean (origin mid-tragion; +x subject's left, +y up, +z out of the
  face; DESIGN 3.1).
* ``vec(X)`` flattens an ``(n, 3)`` array row-major: coordinate ``3*i + axis``
  (axis x=0, y=1, z=2).  All covariances, loadings and whitening matrices use
  this order.
* The energy of a prior is ``E = 0.5 r^T S^-1 r`` with ``r = vec(X - mean)``
  (:meth:`neg_log_density`; the log-determinant constant is dropped).
* ``W`` (:meth:`whiten_matrix`) is the inverse of the lower Cholesky factor of
  ``S``, so ``W^T W = S^-1`` and ``||W r||^2 = r^T S^-1 r``.

The factor prior (DESIGN 4.6)
-----------------------------
``S_eff = K S' K + L_d L_d^T + G Lambda_g G^T + R_floor`` stored as ``S = L L^T + R``:

* ``S'`` is the sex-specific factor covariance ``L_sex L_sex^T + R_res``
  (``L_sex[:, k] = sigma_k * loading_k``) with the ``size`` column removed unless
  ``include_size`` (D-03: the global log-scale zeta carries size).  With sex
  ``'unspecified'`` (default; never inferred, anat R2.7) it is the moment-matched
  balanced mixture ``mean = (mu_M + mu_F)/2``, ``L = [L_M/sqrt2, L_F/sqrt2, (mu_M - mu_F)/2]``,
  i.e. ``S = (S_M + S_F)/2 + delta delta^T/4`` (anat R5.5).
* ``K = diag(kappa)`` per coordinate: 1.5 for an unknown population with 2.5 on
  the x coordinates of al, ac and en; 1.0 for a declared matched population
  (anat R4.4).  No ancestry, race or ethnicity parameter exists (anat R7.4).
* ``L_d``: the extra face-depth factor, sigma 6 mm, ``dz = 1`` on every landmark
  except t, sa, sba, eu, op, v (research ``engine_prior_defaults``
  ``tragion_to_face_depth_extra_sd_mm``; the +/-8 mm t-to-face offset).
* ``G Lambda_g G^T``: rigid invariance, translation sigma 100 mm and rotation
  sigma 0.5 rad, so the prior constrains shape, not pose.
* ``R_floor``: tragion residual (1.0, 1.5, 2.0) mm on t_L and t_R; the source has
  zero variance there by frame construction.  Following the DESIGN 4.6 formula
  the floor is added *after* kappa (it models definition noise, not population
  spread).

All of these defaults are provisional (badges 🧠 / 🆕) and read from the
packaged JSON ``defaults`` block.

Generalised interface
---------------------
Every prior here also offers ``residual(X_all)`` -> ``(m,)`` and
``jacobian(X_all)`` -> ``(m, 3N)`` over a global point array ``X_all (N, 3)``.
For the Gaussian priors the residual is ``W vec(X_all[index] - mean)`` on the
prior's global ``index`` (bind one with :meth:`FactorPrior.with_index`).  Priors
that only provide this interface (e.g. the conditional template prior of WP-08,
which spans a joint index set) can be stacked with Gaussian ones in
:class:`CompositePrior`.
"""
