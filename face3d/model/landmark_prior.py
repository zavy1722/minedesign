# =========================================================================== protocols
@runtime_checkable
class LandmarkPrior(Protocol):
    """A Gaussian prior on the stacked coordinates of ``len(ids)`` landmarks.

    ``meta`` carries at least ``'rigid_invariant'`` (bool: the prior is flat along
    rigid motions, so the solver must fix the gauge itself), ``'source'`` and
    ``'badge'``.
    """

    ids: list[str]
    meta: dict[str, Any]

    def mean(self) -> np.ndarray: ...                      # (n, 3) mm
    def cov(self) -> np.ndarray: ...                       # (3n, 3n) mm^2
    def solve(self, r: np.ndarray) -> np.ndarray: ...      # S^-1 r
    def whiten_matrix(self) -> np.ndarray: ...             # W, W^T W = S^-1
    def whiten(self, r: np.ndarray) -> np.ndarray: ...     # W r
    def neg_log_density(self, X: np.ndarray) -> float: ...  # 0.5 r^T S^-1 r
    def subset(self, ids: Sequence[str]) -> "LandmarkPrior": ...  # marginal prior


@runtime_checkable
class GeneralisedPrior(Protocol):
    """Optional generalised interface: whitened residuals over a global point array.

    ``X_all`` is ``(N, 3)`` (mm).  ``residual`` returns ``(m,)`` whitened residuals
    whose squared norm is twice the prior energy; ``jacobian`` returns
    ``d residual / d vec(X_all)`` with shape ``(m, 3N)``.
    """

    def residual(self, X_all: np.ndarray) -> np.ndarray: ...
    def jacobian(self, X_all: np.ndarray) -> np.ndarray: ...


# =========================================================================== helpers
def _coord_name(ids: Sequence[str], k: int) -> str:
    return f"{ids[k // 3]}.{_AXES[k % 3]}"


def _offending_coords(M: np.ndarray, ids: Sequence[str]) -> list[int]:
    """Coordinates responsible for M not being positive definite."""
    d = np.diag(M)
    scale = float(np.max(np.abs(d))) if d.size else 0.0
    bad = np.flatnonzero(d <= 1e-12 * max(scale, 1e-300))
    if bad.size:
        return [int(k) for k in bad]
    w, V = np.linalg.eigh(0.5 * (M + M.T))
    neg = w <= 1e-12 * max(float(np.max(np.abs(w))), 1e-300)
    if not neg.any():
        return []
    mag = np.max(np.abs(V[:, neg]), axis=1)
    return [int(k) for k in np.flatnonzero(mag >= 0.25 * float(mag.max()))]


def _cholesky_or_raise(M: np.ndarray, ids: Sequence[str], what: str) -> np.ndarray:
    """Lower Cholesky factor of M, or ValueError naming the offending landmark ids."""
    try:
        return np.linalg.cholesky(M)
    except np.linalg.LinAlgError:
        coords = _offending_coords(M, ids)
        bad_ids = list(dict.fromkeys(ids[k // 3] for k in coords))
        detail = ", ".join(_coord_name(ids, k) for k in coords[:24])
        raise ValueError(f"{what} is not symmetric positive definite; offending ids {bad_ids} "
                         f"(coordinates: {detail or 'not isolated'})") from None


def _lower_inverse(Lc: np.ndarray) -> np.ndarray:
    """Inverse of a lower-triangular factor (dense; m <= a few hundred here)."""
    W = np.linalg.solve(Lc, np.eye(Lc.shape[0]))
    return np.tril(W)


def _readonly(a: np.ndarray) -> np.ndarray:
    a.setflags(write=False)
    return a


def _coord_cols(index: np.ndarray) -> np.ndarray:
    """Global coordinate columns (3*index + axis) for landmark rows ``index``."""
    return (3 * np.asarray(index, dtype=np.int64)[:, None] + np.arange(3)).reshape(-1)


def rigid_tangent_basis(mean: np.ndarray) -> tuple[np.ndarray, float]:
    """Unit rigid tangent basis G (3n, 6) at ``mean`` (n, 3) and the RMS radius.

    Columns 0-2: unit translation along x, y, z (1 mm per landmark).  Columns 3-5:
    infinitesimal rotation about x, y, z through the centroid c,
    ``e_k x (mu_i - c) / r_rms`` with ``r_rms = sqrt(mean_i |mu_i - c|^2)`` (so the
    rotation columns move a landmark at the RMS radius by about 1 mm per unit).
    """
    mu = np.asarray(mean, float).reshape(-1, 3)
    D = mu - mu.mean(axis=0)
    r_rms = float(np.sqrt(np.mean(np.sum(D * D, axis=1))))
    if r_rms <= 0.0:
        raise ValueError("rigid basis needs at least two distinct points")
    n = len(mu)
    G = np.zeros((3 * n, 6))
    eye = np.eye(3)
    for k in range(3):
        G[k::3, k] = 1.0
        G[:, 3 + k] = (np.cross(eye[k], D) / r_rms).reshape(-1)
    return G, r_rms


# =========================================================================== package
_PACKAGE_CACHE: dict[tuple[str, int, int], tuple[dict[str, Any], str]] = {}


def _read_package(path: Path) -> tuple[dict[str, Any], str]:
    st = path.stat()
    key = (str(path), st.st_mtime_ns, st.st_size)
    hit = _PACKAGE_CACHE.get(key)
    if hit is None:
        raw = path.read_bytes()
        doc = json.loads(raw.decode("utf-8"))
        if doc.get("format") != "face3d.landmark_prior" or int(doc.get("version", -1)) != 1:
            raise ValueError(f"{path} is not a face3d.landmark_prior v1 file")
        hit = (doc, hashlib.sha256(raw).hexdigest())
        _PACKAGE_CACHE.clear()
        _PACKAGE_CACHE[key] = hit
    return hit


def load_prior_package(path: str | Path | None = None) -> dict[str, Any]:
    """Read the packaged prior JSON into fresh numpy arrays.

    Returns ``{ids, names, factor_names, frame, sha256, path, defaults, source, badge,
    status, sexes: {'M'|'F': {mean (44,3), factor_sigma (18,), loadings (132,18)}},
    residual_cov (132,132), residual_total (44,3), residual_asym (44,3)}``; loadings
    have sigma NOT applied (DESIGN 3.2).
    """
    p = Path(path) if path is not None else PACKAGE_PRIOR_PATH
    doc, sha = _read_package(p)
    n = len(doc["ids"])
    K = len(doc["factor_names"])
    sexes = {}
    for code, s in doc["sexes"].items():
        mean = np.array(s["mean"], float).reshape(n, 3)
        sig = np.array(s["factor_sigma"], float).reshape(K)
        lo = np.array(s["loadings"], float).reshape(3 * n, K)
        sexes[code] = {"mean": mean, "factor_sigma": sig, "loadings": lo}
    return {
        "ids": list(doc["ids"]), "names": list(doc["names"]), "factor_names": list(doc["factor_names"]),
        "frame": doc["frame"], "sha256": sha, "path": str(p), "defaults": copy.deepcopy(doc["defaults"]),
        "source": copy.deepcopy(doc["source"]), "badge": doc.get("badge", ""), "status": doc.get("status", ""),
        "sexes": sexes,
        "residual_cov": np.array(doc["residual_cov"], float).reshape(3 * n, 3 * n),
        "residual_total": np.array(doc["residual_total"], float).reshape(n, 3),
        "residual_asym": np.array(doc["residual_asym"], float).reshape(n, 3),
    }


def prior_mean(sex: str = "unspecified", path: str | Path | None = None) -> tuple[list[str], np.ndarray]:
    """(ids, mean (44, 3) mm) of the packaged prior; 'unspecified' = average of the sexes."""
    pkg = load_prior_package(path)
    if sex == "unspecified":
        mu = 0.5 * (pkg["sexes"]["M"]["mean"] + pkg["sexes"]["F"]["mean"])
    elif sex in _SEX_CODE:
        mu = pkg["sexes"][_SEX_CODE[sex]]["mean"]
    else:
        raise ValueError(f"sex must be 'unspecified', 'male' or 'female', not {sex!r}")
    return pkg["ids"], mu


# =========================================================================== base class
class _GaussianPrior:
    """Shared machinery of the Gaussian landmark priors (mean + covariance)."""

    ids: list[str]
    meta: dict[str, Any]
    index: np.ndarray | None
    _mean: np.ndarray

    _DEFAULT_META = {"rigid_invariant": False, "source": "user-supplied", "badge": "🆕"}

    def _init_common(self, mean: Any, ids: Sequence[str] | None, meta: Mapping[str, Any] | None,
                     index: Any) -> None:
        mu = np.asarray(mean, dtype=float)
        if mu.ndim == 1 and mu.size % 3 == 0:
            mu = mu.reshape(-1, 3)
        if mu.ndim != 2 or mu.shape[1] != 3 or not np.all(np.isfinite(mu)):
            raise ValueError(f"mean must be a finite (n, 3) array, got shape {np.shape(mean)}")
        self._mean = _readonly(mu.copy())
        n = len(mu)
        self.ids = [str(i) for i in ids] if ids is not None else [f"p{i}" for i in range(n)]
        if len(self.ids) != n:
            raise ValueError(f"{len(self.ids)} ids for {n} landmarks")
        if len(set(self.ids)) != n:
            raise ValueError("landmark ids must be unique")
        m = dict(self._DEFAULT_META)
        if meta:
            m.update(meta)
        self.meta = m
        self.index = None if index is None else self._check_index(index)
        self._cache: dict[str, np.ndarray] = {}

    # ------------------------------------------------------------------ basics
    @property
    def n(self) -> int:
        return len(self.ids)

    def mean(self) -> np.ndarray:
        """Prior mean (n, 3) in mm (a copy)."""
        return self._mean.copy()

    def _vec(self, X: Any) -> np.ndarray:
        a = np.asarray(X, dtype=float)
        if a.shape == (self.n, 3):
            return a.reshape(-1)
        if a.shape == (3 * self.n,):
            return a
        raise ValueError(f"expected ({self.n}, 3) or ({3 * self.n},) coordinates, got {a.shape}")

    def _local(self, key: Any) -> int:
        if isinstance(key, (int, np.integer)):
            k = int(key)
            if not 0 <= k < self.n:
                raise IndexError(f"landmark index {k} out of range")
            return k
        try:
            return self.ids.index(str(key))
        except ValueError:
            raise KeyError(f"landmark {key!r} is not in this prior") from None

    def whiten(self, r: Any) -> np.ndarray:
        """W r for r (3n,) or (3n, k)."""
        return self.whiten_matrix() @ np.asarray(r, float)

    def neg_log_density(self, X: Any) -> float:
        """0.5 r^T S^-1 r with r = vec(X - mean); X (n, 3) or (3n,), mm."""
        r = self._vec(X) - self._mean.reshape(-1)
        return 0.5 * float(r @ self.solve(r))

    def marginal_sd(self) -> np.ndarray:
        """Per-coordinate marginal SD (n, 3) in mm."""
        return np.sqrt(np.clip(np.diag(self.cov()), 0.0, None)).reshape(-1, 3)

    def precision(self) -> np.ndarray:
        """S^-1 (3n, 3n)."""
        if "precision" not in self._cache:
            P = self.solve(np.eye(3 * self.n))
            self._cache["precision"] = _readonly(0.5 * (P + P.T))
        return self._cache["precision"]

    def chord_sd(self, a: Any, b: Any) -> float:
        """SD (mm) of the chord |X_a - X_b|, linearised at the mean: sqrt(g^T S g)."""
        ia, ib = self._local(a), self._local(b)
        d = self._mean[ia] - self._mean[ib]
        length = float(np.linalg.norm(d))
        if length == 0.0:
            raise ValueError(f"chord {a}-{b} has zero length at the mean")
        g = np.zeros(3 * self.n)
        g[3 * ia:3 * ia + 3] = d / length
        g[3 * ib:3 * ib + 3] = -d / length
        return math.sqrt(max(float(g @ self._cov_times(g)), 0.0))

    def _cov_times(self, g: np.ndarray) -> np.ndarray:
        return self.cov() @ g

    # ------------------------------------------------------------------ gauge
    def _resolve_anchors(self, anchor_ids: Sequence[Any] | None) -> list[int]:
        if anchor_ids is None:
            idx = [k for k, lid in enumerate(self.ids) if lid in ANATOMICAL and ANATOMICAL[lid].is_anchor]
            if not idx:
                raise ValueError("no registry gauge anchors among this prior's ids; pass anchor_ids")
            return idx
        out: list[int] = []
        for a in anchor_ids:
            if isinstance(a, (int, np.integer)) or str(a) in self.ids:
                out.append(self._local(a))
                continue
            expanded = [k for k, lid in enumerate(self.ids) if landmark_base(lid) == str(a)]
            if not expanded:
                raise KeyError(f"anchor {a!r} is neither an id nor a base of this prior")
            out.extend(expanded)
        return list(dict.fromkeys(out))

    def rigid_gauge_rows(self, anchor_ids: Sequence[Any] | None = None) -> np.ndarray:
        """Six unit-norm gauge rows G_a (6, 3n) on the anchors (DESIGN 4.6).

        Rows 0-2: mean over anchors of the x / y / z displacement.  Rows 3-5:
        ``sum_i (e_k x (mu_i - mu_bar)) . dX_i / r_rms`` (infinitesimal rotation
        about axis k through the anchor centroid mu_bar).  Each row is normalised to
        unit norm.  ``anchor_ids``: ids, bases (``'en'`` -> en_L, en_R) or local
        indices; default = the registry anchors (en, ex, p, n, prn, sn, ch, ls, li,
        sto) present in this prior.  The solver applies them to ``X - mean`` with
        sigma 0.01 mm to fix rotation and translation without biasing shape.
        """
        A = self._resolve_anchors(anchor_ids)
        if len(A) < 3:
            raise ValueError(f"rigid gauge needs at least 3 anchors, got {len(A)}")
        mu = self._mean[A]
        D = mu - mu.mean(axis=0)
        r_rms = float(np.sqrt(np.mean(np.sum(D * D, axis=1))))
        cols = _coord_cols(np.array(A))
        G = np.zeros((6, 3 * self.n))
        eye = np.eye(3)
        for k in range(3):
            G[k, cols[k::3]] = 1.0 / len(A)
            G[3 + k, cols] = (np.cross(eye[k], D) / max(r_rms, 1e-300)).reshape(-1)
        norms = np.linalg.norm(G, axis=1)
        if np.any(norms < 1e-12):
            raise ValueError("gauge anchors are degenerate (collinear or coincident)")
        return G / norms[:, None]

    # ------------------------------------------------------- generalised interface
    def _check_index(self, index: Any) -> np.ndarray:
        idx = np.array(index, dtype=np.int64).reshape(-1)  # own copy (flags set below)
        if idx.shape != (self.n,):
            raise ValueError(f"index must have one global row per landmark ({self.n}), got {idx.shape}")
        if np.any(idx < 0):
            raise ValueError("global index must be non-negative")
        if len(np.unique(idx)) != len(idx):
            raise ValueError("global index has duplicate rows")
        idx.setflags(write=False)
        return idx

    def with_index(self, index: Any):
        """A copy bound to global rows ``index`` (n,) of ``X_all`` (shares cached factors)."""
        out = copy.copy(self)
        out.meta = dict(self.meta)
        out.index = self._check_index(index)
        return out

    def _rows(self, X_all: Any, index: Any) -> tuple[np.ndarray, np.ndarray]:
        X = np.asarray(X_all, dtype=float)
        if X.ndim == 1 and X.size % 3 == 0:
            X = X.reshape(-1, 3)
        if X.ndim != 2 or X.shape[1] != 3:
            raise ValueError(f"X_all must be (N, 3), got {np.shape(X_all)}")
        idx = self._check_index(index) if index is not None else self.index
        if idx is None:
            if len(X) != self.n:
                raise ValueError(f"X_all has {len(X)} rows but this prior (no global index bound) has {self.n}")
            idx = np.arange(self.n)
        elif np.any(idx >= len(X)):
            raise ValueError(f"global index exceeds X_all rows ({len(X)})")
        return X, idx

    def residual(self, X_all: Any, index: Any = None) -> np.ndarray:
        """Whitened residual W vec(X_all[index] - mean), (3n,)."""
        X, idx = self._rows(X_all, index)
        return self.whiten(X[idx].reshape(-1) - self._mean.reshape(-1))

    def jacobian(self, X_all: Any, index: Any = None) -> np.ndarray:
        """d residual / d vec(X_all): (3n, 3N), W scattered into the global columns."""
        X, idx = self._rows(X_all, index)
        J = np.zeros((3 * self.n, 3 * len(X)))
        J[:, _coord_cols(idx)] = self.whiten_matrix()
        return J


# =========================================================================== FactorPrior
class FactorPrior(_GaussianPrior):
    """Low-rank-plus-residual Gaussian prior: S = L L^T + R (DESIGN D-04, 4.6).

    Parameters
    ----------
    mean : (n, 3) mm.
    L : (3n, K) factor loadings with sigma applied (mm); K may be 0.
    R : (3n, 3n) symmetric residual covariance (mm^2); must be positive definite
        for any inverse (``solve``, ``whiten_matrix``, ``neg_log_density``,
        ``residual``).  The check is a Cholesky factorisation done on first use;
        failure raises ``ValueError`` naming the offending ids.  A degenerate R is
        accepted for covariance-only diagnostics (``cov``, ``chord_sd``,
        ``marginal_sd``, ``subset``).
    ids : landmark ids (default ``p0..``).
    meta : dict merged over ``{'rigid_invariant': False, 'source': ..., 'badge': ...}``.
    index : optional global rows of the landmarks in ``X_all`` (generalised interface).
    """

    def __init__(self, mean: Any, L: Any, R: Any, ids: Sequence[str] | None = None,
                 meta: Mapping[str, Any] | None = None, *, index: Any = None):
        self._init_common(mean, ids, meta, index)
        m = 3 * self.n
        Lm = np.asarray(L, dtype=float)
        if Lm.ndim == 1:
            Lm = Lm[:, None]
        if Lm.ndim != 2 or Lm.shape[0] != m or not np.all(np.isfinite(Lm)):
            raise ValueError(f"L must be a finite ({m}, K) array, got shape {np.shape(L)}")
        Rm = np.asarray(R, dtype=float)
        if Rm.shape != (m, m) or not np.all(np.isfinite(Rm)):
            raise ValueError(f"R must be a finite ({m}, {m}) array, got shape {np.shape(R)}")
        asym = float(np.max(np.abs(Rm - Rm.T))) if m else 0.0
        if asym > 1e-9 * max(1.0, float(np.max(np.abs(Rm)))):
            raise ValueError(f"R is not symmetric (max |R - R^T| = {asym:g})")
        self.L = _readonly(Lm.copy())
        self.R = _readonly(0.5 * (Rm + Rm.T))

    @property
    def n_factors(self) -> int:
        return self.L.shape[1]

    # ------------------------------------------------------------------ algebra
    def cov(self) -> np.ndarray:
        """S = L L^T + R (3n, 3n), mm^2 (cached, read-only)."""
        if "cov" not in self._cache:
            self._cache["cov"] = _readonly(self.L @ self.L.T + self.R)
        return self._cache["cov"]

    def _cov_times(self, g: np.ndarray) -> np.ndarray:
        return self.L @ (self.L.T @ g) + self.R @ g

    def _r_inverse_factor(self) -> np.ndarray:
        if "Wr" not in self._cache:
            Lr = _cholesky_or_raise(self.R, self.ids, "residual covariance R")
            self._cache["Wr"] = _readonly(_lower_inverse(Lr))
        return self._cache["Wr"]

    def check_spd(self) -> None:
        """Raise ``ValueError`` naming the offending ids unless R (hence S) is SPD."""
        self._r_inverse_factor()

    def _r_solve(self, b: np.ndarray) -> np.ndarray:
        Wr = self._r_inverse_factor()
        return Wr.T @ (Wr @ b)

    def solve(self, r: Any) -> np.ndarray:
        """S^-1 r by Woodbury with the Cholesky factor of R (r: (3n,) or (3n, k)).

        S^-1 r = R^-1 r - R^-1 L (I + L^T R^-1 L)^-1 L^T R^-1 r   (DESIGN 4.6).
        """
        b = np.asarray(r, dtype=float)
        if b.shape[0] != 3 * self.n:
            raise ValueError(f"expected {3 * self.n} rows, got {b.shape}")
        y = self._r_solve(b)
        if self.n_factors == 0:
            return y
        if "RinvL" not in self._cache:
            RinvL = self._r_solve(self.L)
            C = np.eye(self.n_factors) + self.L.T @ RinvL
            Cc = np.linalg.cholesky(0.5 * (C + C.T))  # SPD whenever R is
            self._cache["RinvL"] = _readonly(RinvL)
            self._cache["Wc"] = _readonly(_lower_inverse(Cc))
        RinvL, Wc = self._cache["RinvL"], self._cache["Wc"]
        z = Wc.T @ (Wc @ (self.L.T @ y))
        return y - RinvL @ z

    def whiten_matrix(self) -> np.ndarray:
        """W = inverse of the lower Cholesky factor of S (3n, 3n; cached, read-only)."""
        if "W" not in self._cache:
            self.check_spd()
            Lc = _cholesky_or_raise(self.cov(), self.ids, "prior covariance S")
            self._cache["W"] = _readonly(_lower_inverse(Lc))
        return self._cache["W"]

    # ------------------------------------------------------------------ marginals
    def subset(self, ids: Sequence[Any]) -> "FactorPrior":
        """Marginal prior of ``ids`` (rows of L and the R sub-block; same columns)."""
        loc = [self._local(i) for i in ids]
        if len(set(loc)) != len(loc):
            raise ValueError("subset ids must be unique")
        rows = _coord_cols(np.array(loc, dtype=np.int64)) if loc else np.zeros(0, np.int64)
        index = None if self.index is None else self.index[loc]
        return FactorPrior(self._mean[loc], self.L[rows], self.R[np.ix_(rows, rows)],
                           ids=[self.ids[k] for k in loc], meta=dict(self.meta), index=index)

    # ------------------------------------------------------------------ package
    @classmethod
    def from_package(cls, sex: str = "unspecified", population: str = "unknown", include_size: bool = False,
                     extra_depth_sigma_mm: float = 6.0, rigid_invariance: bool = True, tragion_floor: bool = True,
                     ids: Sequence[str] | None = None, path: str | Path | None = None) -> "FactorPrior":
        """The default 44-landmark, 18-factor prior from ``face3d/data/landmark_prior_v1.json``.

        Parameters
        ----------
        sex : 'unspecified' (default; balanced moment-matched mixture, anat R5.5), or a
            declared, consented 'male' / 'female' (never inferred, anat R2.7).
        population : 'unknown' (kappa 1.5, 2.5 on al/ac/en x) or 'matched' (kappa 1.0)
            (anat R4.4).  This is not an ancestry label and none is stored (anat R7.4).
        include_size : keep the isometric ``size`` factor (default off: the global
            log-scale zeta is the single population size source, D-03).
        extra_depth_sigma_mm : extra face-depth factor sigma (6 mm default, research
            ``engine_prior_defaults``); 0 disables it.
        rigid_invariance : append the rigid columns (translation 100 mm, rotation 0.5 rad)
            and set ``meta['rigid_invariant']``.
        tragion_floor : add the (1.0, 1.5, 2.0) mm tragion residual floor to R.
        ids : optional subset of ids (marginal prior, in the given order).
        path : alternative package file.
        """
        if sex not in ("unspecified", "male", "female"):
            raise ValueError(f"sex must be 'unspecified', 'male' or 'female', not {sex!r}")
        if population not in ("unknown", "matched"):
            raise ValueError(f"population must be 'unknown' or 'matched', not {population!r}")
        if not extra_depth_sigma_mm >= 0.0:
            raise ValueError("extra_depth_sigma_mm must be >= 0")
        pkg = load_prior_package(path)
        dflt = pkg["defaults"]
        all_ids = pkg["ids"]
        n = len(all_ids)
        fnames = pkg["factor_names"]
        keep = [k for k, f in enumerate(fnames) if include_size or f != "size"]

        def sex_factors(code: str) -> np.ndarray:
            s = pkg["sexes"][code]
            return (s["loadings"] * s["factor_sigma"][None, :])[:, keep]

        if sex == "unspecified":
            mu_M, mu_F = pkg["sexes"]["M"]["mean"], pkg["sexes"]["F"]["mean"]
            mu = 0.5 * (mu_M + mu_F)
            delta = (mu_M - mu_F).reshape(-1, 1)
            L = np.hstack([sex_factors("M") / math.sqrt(2.0), sex_factors("F") / math.sqrt(2.0), 0.5 * delta])
            columns = ([f"M:{fnames[k]}" for k in keep] + [f"F:{fnames[k]}" for k in keep] + ["sex_difference"])
        else:
            code = _SEX_CODE[sex]
            mu = pkg["sexes"][code]["mean"]
            L = sex_factors(code)
            columns = [fnames[k] for k in keep]
        R = pkg["residual_cov"].copy()

        # kappa (anat R4.4): K L, K R K
        if population == "unknown":
            kappa = np.full(3 * n, float(dflt["kappa_unknown"]))
            wide = dflt["kappa_wide"]
            for b, ax in wide["coords"]:
                for i, lid in enumerate(all_ids):
                    if landmark_base(lid) == b:
                        kappa[3 * i + _AXIS[ax]] = float(wide["value"])
            kappa_meta = {"base": float(dflt["kappa_unknown"]), "wide": float(wide["value"]),
                          "wide_coords": [list(c) for c in wide["coords"]]}
        else:
            kappa = np.full(3 * n, float(dflt["kappa_matched"]))
            kappa_meta = {"base": float(dflt["kappa_matched"]), "wide": None, "wide_coords": []}
        L = kappa[:, None] * L
        R = kappa[:, None] * R * kappa[None, :]

        # tragion floor (definition noise; outside K per the DESIGN 4.6 formula)
        if tragion_floor:
            floor = np.asarray(dflt["tragion_floor_mm"], float)
            for i, lid in enumerate(all_ids):
                if landmark_base(lid) == "t":
                    for ax in range(3):
                        R[3 * i + ax, 3 * i + ax] += floor[ax] ** 2

        # extra face-depth factor L_d
        if extra_depth_sigma_mm > 0.0:
            excl = set(dflt["extra_depth"]["exclude"])
            col = np.zeros(3 * n)
            for i, lid in enumerate(all_ids):
                if landmark_base(lid) not in excl:
                    col[3 * i + 2] = float(extra_depth_sigma_mm)
            L = np.hstack([L, col[:, None]])
            columns.append("extra_depth")

        # rigid invariance G Lambda_g G^T
        if rigid_invariance:
            G, r_rms = rigid_tangent_basis(mu)
            rig = dflt["rigid_invariance"]
            t_mm, rot = float(rig["translation_mm"]), float(rig["rotation_rad"])
            scale = np.array([t_mm, t_mm, t_mm, rot * r_rms, rot * r_rms, rot * r_rms])
            L = np.hstack([L, G * scale[None, :]])
            columns += ["rigid_tx", "rigid_ty", "rigid_tz", "rigid_rx", "rigid_ry", "rigid_rz"]

        meta = {
            "rigid_invariant": bool(rigid_invariance),
            "source": {"path": pkg["path"], "sha256": pkg["sha256"], "research": pkg["source"]},
            "badge": pkg["badge"],
            "status": pkg["status"],
            "frame": pkg["frame"],
            "sex": sex,
            "population": population,
            "include_size": bool(include_size),
            "extra_depth_sigma_mm": float(extra_depth_sigma_mm),
            "tragion_floor": bool(tragion_floor),
            "columns": columns,
            "kappa": kappa_meta,
            "scale_sigma_log": float(dflt["scale_sigma_log"]),
        }
        prior = cls(mu, L, R, ids=all_ids, meta=meta)
        if ids is not None:
            prior = prior.subset(ids)
        return prior

    def __repr__(self) -> str:
        return f"FactorPrior(n={self.n}, K={self.n_factors}, rigid_invariant={self.meta.get('rigid_invariant')})"


# =========================================================================== DiagonalPrior
class DiagonalPrior(_GaussianPrior):
    """Independent per-coordinate Gaussian prior: S = diag(sigma^2) (legacy adapter, WP-07).

    ``sigma`` is (n, 3) mm (a scalar or (3,) broadcasts) and must be finite and > 0.
    """

    def __init__(self, mean: Any, sigma: Any, ids: Sequence[str] | None = None,
                 meta: Mapping[str, Any] | None = None, *, index: Any = None):
        self._init_common(mean, ids, meta, index)
        s = np.broadcast_to(np.asarray(sigma, dtype=float), (self.n, 3)).copy()
        bad = ~np.isfinite(s) | (s <= 0.0)
        if bad.any():
            names = [f"{self.ids[i]}.{_AXES[a]}" for i, a in zip(*np.nonzero(bad))]
            raise ValueError(f"DiagonalPrior sigma must be finite and > 0; offending coordinates {names}")
        self.sigma = _readonly(s)
        self._s = s.reshape(-1)

    def cov(self) -> np.ndarray:
        if "cov" not in self._cache:
            self._cache["cov"] = _readonly(np.diag(self._s ** 2))
        return self._cache["cov"]

    def _cov_times(self, g: np.ndarray) -> np.ndarray:
        return self._s ** 2 * g

    def solve(self, r: Any) -> np.ndarray:
        b = np.asarray(r, dtype=float)
        if b.shape[0] != 3 * self.n:
            raise ValueError(f"expected {3 * self.n} rows, got {b.shape}")
        v = self._s ** 2
        return b / (v if b.ndim == 1 else v[:, None])

    def whiten_matrix(self) -> np.ndarray:
        if "W" not in self._cache:
            self._cache["W"] = _readonly(np.diag(1.0 / self._s))
        return self._cache["W"]

    def whiten(self, r: Any) -> np.ndarray:
        b = np.asarray(r, dtype=float)
        return b / (self._s if b.ndim == 1 else self._s[:, None])

    def marginal_sd(self) -> np.ndarray:
        return self.sigma.copy()

    def subset(self, ids: Sequence[Any]) -> "DiagonalPrior":
        loc = [self._local(i) for i in ids]
        if len(set(loc)) != len(loc):
            raise ValueError("subset ids must be unique")
        index = None if self.index is None else self.index[loc]
        return DiagonalPrior(self._mean[loc], self.sigma[loc], ids=[self.ids[k] for k in loc],
                             meta=dict(self.meta), index=index)

    def __repr__(self) -> str:
        return f"DiagonalPrior(n={self.n})"


# =========================================================================== CompositePrior
class CompositePrior:
    """Several priors over one global point array, stacked as whitened residuals.

    ``parts`` items are either ``(prior, index)`` pairs, where ``prior`` is a
    Gaussian prior here and ``index`` the global rows of its landmarks, or objects
    that already implement the generalised interface over ``X_all`` (e.g. a
    ``FactorPrior.with_index(...)`` or WP-08's conditional template prior, which
    spans a joint index set).  Parts may overlap: the energies add,
    ``E = 0.5 ||residual(X_all)||^2 = sum_p E_p``.

    ``whiten_matrix`` is the stacked Jacobian (block-structured in the global
    coordinate order: each part's rows touch only its own columns).  ``mean`` and
    ``cov`` are those of the product of the parts, valid for affine residuals
    (all priors in this package) when every global coordinate is constrained.
    """

    def __init__(self, parts: Sequence[Any], n_total: int, ids: Sequence[str] | None = None,
                 meta: Mapping[str, Any] | None = None):
        self.n_total = int(n_total)
        if self.n_total <= 0:
            raise ValueError("n_total must be positive")
        self.parts: list[Any] = []
        for p in parts:
            if isinstance(p, (tuple, list)):
                if len(p) != 2:
                    raise ValueError("composite parts must be (prior, global_index) pairs or bound priors")
                prior, index = p
                if not hasattr(prior, "with_index"):
                    raise TypeError(f"{type(prior).__name__} cannot be bound to a global index")
                p = prior.with_index(index)
            if not (hasattr(p, "residual") and hasattr(p, "jacobian")):
                raise TypeError(f"{type(p).__name__} lacks the generalised residual/jacobian interface")
            idx = getattr(p, "index", None)
            if isinstance(idx, np.ndarray) and idx.dtype.kind in "iu" and np.any(idx >= self.n_total):
                raise ValueError(f"a part's global index exceeds n_total={self.n_total}")
            self.parts.append(p)
        if not self.parts:
            raise ValueError("CompositePrior needs at least one part")
        self.ids = [str(i) for i in ids] if ids is not None else None
        if self.ids is not None and len(self.ids) != self.n_total:
            raise ValueError(f"{len(self.ids)} ids for n_total={self.n_total}")
        part_meta = [getattr(p, "meta", {}) or {} for p in self.parts]
        m = {
            "rigid_invariant": all(bool(pm.get("rigid_invariant", False)) for pm in part_meta),
            "source": [pm.get("source", type(p).__name__) for pm, p in zip(part_meta, self.parts)],
            "badge": "".join(dict.fromkeys(str(pm.get("badge", "")) for pm in part_meta)),
        }
        if meta:
            m.update(meta)
        self.meta = m

    def _points(self, X_all: Any) -> np.ndarray:
        X = np.asarray(X_all, dtype=float)
        if X.ndim == 1 and X.size == 3 * self.n_total:
            X = X.reshape(-1, 3)
        if X.shape != (self.n_total, 3):
            raise ValueError(f"X_all must be ({self.n_total}, 3), got {np.shape(X_all)}")
        return X

    def part_residuals(self, X_all: Any) -> list[np.ndarray]:
        X = self._points(X_all)
        return [np.asarray(p.residual(X), float).reshape(-1) for p in self.parts]

    def residual(self, X_all: Any) -> np.ndarray:
        """Stacked whitened residuals of all parts (m,)."""
        return np.concatenate(self.part_residuals(X_all))

    def jacobian(self, X_all: Any) -> np.ndarray:
        """Stacked Jacobians (m, 3 n_total) in the global coordinate order."""
        X = self._points(X_all)
        Js = []
        for p in self.parts:
            J = np.asarray(p.jacobian(X), float)
            if J.ndim != 2 or J.shape[1] != 3 * self.n_total:
                raise ValueError(f"part jacobian has shape {J.shape}, expected (m, {3 * self.n_total})")
            Js.append(J)
        return np.vstack(Js)

    def whiten_matrix(self, X_all: Any = None) -> np.ndarray:
        """Block-structured global whitening matrix (m, 3 n_total).

        Exact (state-independent) for affine parts; for a nonlinear part it is the
        Jacobian at ``X_all`` (default: zeros).
        """
        X = np.zeros((self.n_total, 3)) if X_all is None else self._points(X_all)
        return self.jacobian(X)

    def neg_log_density(self, X_all: Any) -> float:
        r = self.residual(X_all)
        return 0.5 * float(r @ r)

    def precision(self, X_all: Any = None) -> np.ndarray:
        """J^T J (3 n_total, 3 n_total)."""
        J = self.whiten_matrix(X_all)
        return J.T @ J

    def _affine_solution(self) -> tuple[np.ndarray, np.ndarray]:
        Z = np.zeros((self.n_total, 3))
        J = self.jacobian(Z)
        c = self.residual(Z)
        H = J.T @ J
        names = self.ids if self.ids is not None else [f"row{i}" for i in range(self.n_total)]
        Lc = _cholesky_or_raise(H, names, "composite precision (some global points unconstrained?)")
        W = _lower_inverse(Lc)
        cov = W.T @ W
        x = -cov @ (J.T @ c)
        return x.reshape(-1, 3), 0.5 * (cov + cov.T)

    def mean(self) -> np.ndarray:
        """Mode of the product of the (affine) parts, (n_total, 3)."""
        return self._affine_solution()[0]

    def cov(self) -> np.ndarray:
        """Covariance of the product of the (affine) parts, (3 n_total, 3 n_total)."""
        return self._affine_solution()[1]

    def __repr__(self) -> str:
        return f"CompositePrior(parts={len(self.parts)}, n_total={self.n_total})"
