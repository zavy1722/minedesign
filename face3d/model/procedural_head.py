"""Procedural CC0 template head: a cube-sphere warped onto the landmark prior mean.

The sandbox default template is generated by our own code, so it is CC0 and
needs no third-party asset (DESIGN 0 Summary, D-28; 3.2 "Template kit"; 4.6
conditional prior).  It is labelled ``generated=True`` and is **not
anatomical**: between the 44 landmarks its shape is an ellipsoid with a few
smooth feature bumps, nothing more (DESIGN 2.1 invariant 6, no fabrication).

Conventions: float64 millimetres in the Frankfort-horizontal frame of the prior
mean (origin mid-tragion; +x subject's left, +y up, +z out of the face; DESIGN
3.1).  The construction is deterministic (no randomness).

Construction (WP-08 spec; every number below is from that spec unless cited
otherwise, badge 🆕 = introduced by this design for a generated asset):

1. **Topology**: cube-sphere, all quads.  Each of the 6 cube faces (axis ``a``,
   sign ``s``) is an ``(n+1)^2`` grid on ``[-1, 1]^2``; shared vertices are
   de-duplicated by the integer key ``round(p * n)``; quads are oriented outward
   (a quad is flipped when ``(b - a) x (c - a) . a < 0``).  ``n`` must be even so
   that exact midline (x = 0) vertices exist.  Points are projected to the unit
   sphere ``p / |p|``.  ``V = 6 n^2 + 2``, ``F = 6 n^2``.
2. **Ellipsoid**: radii ``HEAD_RADII_MM = (76, 112, 102)`` mm, centre
   ``HEAD_CENTRE_MM = (0, 18, 2)`` mm.
3. **Feature bumps** (:data:`BUMPS`), mirror-symmetric anisotropic Gaussians
   along the ellipsoid normal: nose, brow ridges, eye sockets (negative), lips,
   chin, cheekbones, ears.
4. **Landmark warp**: targets are the 44 prior means for ``sex`` from
   ``face3d/data/landmark_prior_v1.json`` (``'unspecified'`` = average of the
   sexes, DESIGN 4.6).  Each midline id takes the midline vertex with the
   smallest angle to the target direction seen from the ellipsoid centre; each
   ``_L`` id the nearest vertex with ``x > 0``; ``_R`` the mirror of its ``_L``
   vertex; collisions go to the next-nearest candidate.  All vertices are warped
   with :class:`face3d.geometry.rbf.RBFWarp` (biharmonic, smoothing 0), then
   symmetrised ``V <- (V + V[m] * (-1, 1, 1)) / 2`` with the midline set to
   ``x = 0``; landmark vertices are snapped onto their (exactly symmetric)
   targets, removing the ~1e-12 mm interpolation round-off.
5. **Fold check**: every fan triangle's normal must keep a positive dot product
   with the undeformed sphere normal, and the signed volume must be positive;
   otherwise all bump amplitudes are scaled by 0.8 and the build retried (at
   most 5 times), else :class:`ProceduralHeadError` is raised.
6. **Regions** (:func:`geometric_regions`; disjoint, first rule wins in the
   order eyes, nose, lips, chin, ears, jaw, cheeks, forehead, scalp, neck,
   other).
7. **Jaw weights** (:func:`jaw_weights_rule`), **stiffness**
   (:func:`stiffness_rule`; DESIGN 4.15 stage C values), area-weighted
   **normals**, **UV** = spherical coordinates of the undeformed sphere.
8. **Landmark embeddings**: ``'anatomical44'`` (one-hot on the assigned vertex)
   and ``'legacy_synthetic'`` (anatomical aliases on the anatomical vertex; the
   other legacy names by a similarity transfer of the legacy fixture, see
   :func:`legacy_synthetic_embeddings`).
"""
