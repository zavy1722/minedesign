def geometric_regions(V: np.ndarray, lm: Mapping[str, Any]) -> dict[str, np.ndarray]:
    """Disjoint regions by the geometric rules of :data:`REGION_RULES_MM` (WP-08 spec).

    ``lm`` maps the anatomical ids of :data:`REGION_LANDMARKS` to (3,) positions (mm).
    Every vertex receives exactly one region, the first rule that matches in
    :data:`REGION_ORDER` (``'other'`` last).  Returns ``{name: sorted int64 ids}``
    in :data:`REGION_ORDER` (empty regions included).
    """
    missing = [k for k in REGION_LANDMARKS if k not in lm]
    if missing:
        raise KeyError(f"geometric regions need anatomical landmarks {missing}")
    V = np.asarray(V, float)
    P = {k: np.asarray(lm[k], float).reshape(3) for k in REGION_LANDMARKS}
    R = REGION_RULES_MM
    x, y, z = V[:, 0], V[:, 1], V[:, 2]
    ax = np.abs(x)

    def near(name: str, r: float) -> np.ndarray:
        return np.linalg.norm(V - P[name], axis=1) < r

    y_lo, y_hi = sorted((P["sn"][1], P["n"][1]))
    rules = {
        "eyes": near("p_L", R["eyes_radius"]) | near("p_R", R["eyes_radius"]),
        "nose": near("prn", R["nose_radius"])
        | ((ax < R["nose_half_width"]) & (y > y_lo) & (y < y_hi) & (z > R["nose_min_z"])),
        "lips": near("sto", R["lips_radius"]) & (ax < R["lips_half_width"]),
        "chin": near("pg", R["chin_radius"]),
        "ears": near("t_L", R["ears_radius"]) | near("t_R", R["ears_radius"]),
        "jaw": near("go_L", R["jaw_radius"]) | near("go_R", R["jaw_radius"])
        | ((y < R["jaw_max_y"]) & (ax > R["jaw_min_abs_x"])),
        "cheeks": (ax > R["cheeks_min_abs_x"]) & (y > R["cheeks_min_y"]) & (y < R["cheeks_max_y"])
        & (z > R["cheeks_min_z"]),
        "forehead": (y > R["forehead_min_y"]) & (z > R["forehead_min_z"]),
        "scalp": (y > R["scalp_min_y"]) | (z < R["scalp_max_z"]),
        "neck": y < R["neck_max_y"],
    }
    free = np.ones(len(V), bool)
    out: dict[str, np.ndarray] = {}
    for name in REGION_ORDER:
        sel = free.copy() if name == "other" else (rules[name] & free)
        out[name] = np.flatnonzero(sel).astype(np.int64)
        free &= ~sel
    return out


def jaw_weights_rule(V: np.ndarray, y_sto: float) -> np.ndarray:
    """Jaw weights (WP-08 spec 🆕; cf. the jaw hinge of DESIGN 4.9).

    ``w = clip((y_sto - y)/20 + 0.5, 0, 1)`` for ``z > -10`` mm, multiplied by the
    lateral fall-off ``clip((60 - |x|)/20, 0, 1)`` where ``|x| > 40`` mm; 0 elsewhere.
    """
    V = np.asarray(V, float)
    J = JAW_RULE_MM
    w = np.clip((float(y_sto) - V[:, 1]) / J["ramp"] + 0.5, 0.0, 1.0)
    ax = np.abs(V[:, 0])
    lat = np.where(ax > J["lateral_inner"], np.clip((J["lateral_outer"] - ax) / J["lateral_ramp"], 0.0, 1.0), 1.0)
    return np.where(V[:, 2] > J["min_z"], w * lat, 0.0)


def stiffness_rule(n_verts: int, edges: np.ndarray, regions: Mapping[str, np.ndarray]) -> np.ndarray:
    """Per-vertex Laplacian stiffness (DESIGN 4.15 stage C; anat R5.9 🧠).

    1.0 base; 3.0 on eye-region boundary vertices (eye vertices with an edge to a
    non-eye vertex: the closed procedural head has no lid margin, so the region
    border stands in for it); 0.3 on lips; 0.5 on forehead.  Values come from the
    ``template_kit`` defaults namespace.
    """
    D = _KIT_DEFAULTS
    s = np.full(int(n_verts), float(D.stiffness_base.value))
    eyes = np.zeros(int(n_verts), bool)
    eyes[np.asarray(regions.get("eyes", []), dtype=np.int64)] = True
    e = np.asarray(edges, dtype=np.int64).reshape(-1, 2)
    cross = eyes[e[:, 0]] != eyes[e[:, 1]]
    border = np.zeros(int(n_verts), bool)
    border[e[cross].reshape(-1)] = True
    s[np.asarray(regions.get("lips", []), dtype=np.int64)] = D.stiffness_lips.value
    s[np.asarray(regions.get("forehead", []), dtype=np.int64)] = D.stiffness_forehead.value
    s[border & eyes] = D.stiffness_eye_boundary.value
    return s


def region_weights_default() -> dict[str, float]:
    """Region weights from the ``template_kit`` defaults (open-template-head-kit Table 4)."""
    return {r: float(_KIT_DEFAULTS[f"weight_{r}"].value) for r in REGION_ORDER}


