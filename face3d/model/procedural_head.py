# =========================================================================== topology
def cube_sphere(n: int) -> dict[str, np.ndarray]:
    """All-quad cube-sphere of resolution ``n`` (even).

    Returns ``{'keys' (V,3) int64 = round(p*n) of the cube point, 'cube' (V,3) cube
    points on [-1,1]^3, 'sphere' (V,3) unit-sphere points, 'faces' (F,4) int64
    outward-oriented quads, 'mirror_map' (V,) the x -> -x vertex map, 'midline' (k,)
    vertices with x = 0}``.  Vertex order is the first appearance in the loop over
    axis a = 0, 1, 2, sign +1, -1, grid i, j (deterministic).
    """
    n = int(n)
    if n < 2 or n % 2:
        raise ValueError(f"n must be an even integer >= 2 (exact midline vertices), got {n}")
    index: dict[tuple[int, int, int], int] = {}
    keys: list[tuple[int, int, int]] = []
    faces: list[list[int]] = []
    for a in range(3):
        b, c = (a + 1) % 3, (a + 2) % 3
        for s in (1, -1):
            grid = np.empty((n + 1, n + 1), dtype=np.int64)
            for i in range(n + 1):
                for j in range(n + 1):
                    k = [0, 0, 0]
                    k[a] = s * n
                    k[b] = -n + 2 * i
                    k[c] = -n + 2 * j
                    key = (k[0], k[1], k[2])
                    if key not in index:
                        index[key] = len(keys)
                        keys.append(key)
                    grid[i, j] = index[key]
            for i in range(n):
                for j in range(n):
                    q = [int(grid[i, j]), int(grid[i + 1, j]), int(grid[i + 1, j + 1]), int(grid[i, j + 1])]
                    pa, pb, pc = (np.asarray(keys[q[t]], float) for t in range(3))
                    if float(np.dot(np.cross(pb - pa, pc - pa), pa)) < 0.0:
                        q = [q[0], q[3], q[2], q[1]]
                    faces.append(q)
    K = np.asarray(keys, dtype=np.int64)
    cube = K.astype(np.float64) / n
    sphere = cube / np.linalg.norm(cube, axis=1, keepdims=True)
    mirror = np.asarray([index[(-k[0], k[1], k[2])] for k in keys], dtype=np.int64)
    midline = np.flatnonzero(K[:, 0] == 0).astype(np.int64)
    sphere[midline, 0] = 0.0
    return {"keys": K, "cube": cube, "sphere": sphere, "faces": np.asarray(faces, dtype=np.int64),
            "mirror_map": mirror, "midline": midline}


def spherical_uv(S: np.ndarray) -> np.ndarray:
    """Per-vertex UV of unit-sphere points: u = 0.5 + atan2(x, z)/(2 pi), v = 0.5 + asin(y)/pi."""
    S = np.asarray(S, float)
    u = 0.5 + np.arctan2(S[:, 0], S[:, 2]) / (2.0 * math.pi)
    v = 0.5 + np.arcsin(np.clip(S[:, 1], -1.0, 1.0)) / math.pi
    return np.stack([u, v], axis=1)


def signed_volume(V: np.ndarray, tris: np.ndarray) -> float:
    """Enclosed signed volume (mm^3) of a closed triangle mesh; positive when outward-oriented."""
    V = np.asarray(V, float)
    a, b, c = V[tris[:, 0]], V[tris[:, 1]], V[tris[:, 2]]
    return float(np.einsum("ij,ij->i", a, np.cross(b, c)).sum() / 6.0)


def fold_check(V: np.ndarray, S: np.ndarray, faces: np.ndarray) -> tuple[bool, float, float]:
    """Fold check of step 5: ``(ok, min_dot, volume)``.

    ``min_dot`` is the smallest cosine between a fan triangle's normal and the
    undeformed sphere normal at that triangle (the normalised mean of its unit-sphere
    corners); ``ok`` requires ``min_dot > 0`` and a positive signed volume.
    """
    tris = fan_triangles(faces)
    V = np.asarray(V, float)
    fn = np.cross(V[tris[:, 1]] - V[tris[:, 0]], V[tris[:, 2]] - V[tris[:, 0]])
    ns = S[tris].sum(axis=1)
    cosv = np.einsum("ij,ij->i", fn, ns) / np.maximum(
        np.linalg.norm(fn, axis=1) * np.linalg.norm(ns, axis=1), 1e-300)
    vol = signed_volume(V, tris)
    min_dot = float(cosv.min())
    return bool(min_dot > 0.0 and vol > 0.0), min_dot, vol


# =========================================================================== shape
def _bump_height(E: np.ndarray, amp_scale: float) -> np.ndarray:
    h = np.zeros(len(E))
    for _name, c, sig, amp, mirrored in BUMPS:
        centres = [np.asarray(c, float)]
        if mirrored and c[0] != 0.0:
            centres.append(np.asarray(c, float) * np.array([-1.0, 1.0, 1.0]))
        sig_a = np.asarray(sig, float)
        for cc in centres:
            d = (E - cc) / sig_a
            h += amp_scale * amp * np.exp(-0.5 * np.sum(d * d, axis=1))
    return h


def _ellipsoid(S: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    R = np.asarray(HEAD_RADII_MM, float)
    C = np.asarray(HEAD_CENTRE_MM, float)
    E = C + S * R
    N = S / R
    N /= np.linalg.norm(N, axis=1, keepdims=True)
    return E, N


def _side(lid: str) -> str:
    return ANATOMICAL[lid].side if lid in ANATOMICAL else ("L" if lid.endswith("_L") else
                                                           "R" if lid.endswith("_R") else "mid")


def _assign(V0: np.ndarray, ids: Sequence[str], T: np.ndarray, midline: np.ndarray,
            mirror: np.ndarray) -> np.ndarray:
    """Step 4 assignment of one vertex per anatomical id (see module docstring)."""
    C = np.asarray(HEAD_CENTRE_MM, float)
    pos = {lid: k for k, lid in enumerate(ids)}
    out = np.full(len(ids), -1, dtype=np.int64)
    taken: set[int] = set()
    left = np.flatnonzero(V0[:, 0] > 1e-9)
    mid = midline[np.abs(V0[midline, 0]) < 1e-9]
    Dm = V0[mid] - C
    Dm_n = Dm / np.linalg.norm(Dm, axis=1, keepdims=True)
    for k, lid in enumerate(ids):
        side = _side(lid)
        if side == "R":
            continue
        if side == "mid":
            t = T[k] - C
            cosv = Dm_n @ (t / np.linalg.norm(t))
            ang = np.arccos(np.clip(cosv, -1.0, 1.0))
            order = mid[np.argsort(ang, kind="stable")]
        else:
            d = np.linalg.norm(V0[left] - T[k], axis=1)
            order = left[np.argsort(d, kind="stable")]
        for v in order:
            if int(v) not in taken:
                out[k] = int(v)
                taken.add(int(v))
                break
        else:  # pragma: no cover - only for absurdly coarse meshes
            raise ProceduralHeadError(f"no free vertex left for landmark {lid!r}")
    for k, lid in enumerate(ids):
        if _side(lid) == "R":
            lk = pos.get(lid[:-2] + "_L")
            if lk is None:
                raise ValueError(f"right-side landmark {lid!r} has no left partner")
            out[k] = int(mirror[out[lk]])
    return out


