def _one_hot(first_tri: np.ndarray, corner: np.ndarray, v: int, sigma: float, provenance: str) -> dict[str, Any]:
    b = np.zeros(3)
    b[int(corner[v])] = 1.0
    return {"tri": int(first_tri[v]), "bary": b, "sigma_annot_mm": float(sigma), "provenance": provenance}


